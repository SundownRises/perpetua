/**
 * Copies the ABIs the frontend needs out of the Hardhat artifacts into
 * web/lib/abi.ts, so the UI can never drift from the compiled contracts.
 *
 *   node scripts/export-abi.mjs
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, "..");

const WANTED = {
  perpetuaLockerAbi: "contracts/PerpetuaLocker.sol/PerpetuaLocker.json",
  lveBtcAbi: "contracts/LveBTC.sol/LveBTC.json",
  streamerAbi: "contracts/MUSDRewardStreamer.sol/MUSDRewardStreamer.json",
};

/** Minimal ERC-20 surface; the BTC facade and MUSD both present this. */
const ERC20_ABI = [
  { type: "function", name: "balanceOf", stateMutability: "view", inputs: [{ name: "a", type: "address" }], outputs: [{ type: "uint256" }] },
  { type: "function", name: "allowance", stateMutability: "view", inputs: [{ name: "o", type: "address" }, { name: "s", type: "address" }], outputs: [{ type: "uint256" }] },
  { type: "function", name: "approve", stateMutability: "nonpayable", inputs: [{ name: "s", type: "address" }, { name: "v", type: "uint256" }], outputs: [{ type: "bool" }] },
  { type: "function", name: "decimals", stateMutability: "view", inputs: [], outputs: [{ type: "uint8" }] },
  { type: "function", name: "symbol", stateMutability: "view", inputs: [], outputs: [{ type: "string" }] },
  { type: "function", name: "totalSupply", stateMutability: "view", inputs: [], outputs: [{ type: "uint256" }] },
];

/** The slice of Mezo's VeBTCVoter the UI reads to show gauge weights. */
const VOTER_ABI = [
  { type: "function", name: "length", stateMutability: "view", inputs: [], outputs: [{ type: "uint256" }] },
  { type: "function", name: "pools", stateMutability: "view", inputs: [{ name: "i", type: "uint256" }], outputs: [{ type: "address" }] },
  { type: "function", name: "gauges", stateMutability: "view", inputs: [{ name: "p", type: "address" }], outputs: [{ type: "address" }] },
  { type: "function", name: "votes", stateMutability: "view", inputs: [{ name: "id", type: "uint256" }, { name: "p", type: "address" }], outputs: [{ type: "uint256" }] },
  { type: "function", name: "usedWeights", stateMutability: "view", inputs: [{ name: "id", type: "uint256" }], outputs: [{ type: "uint256" }] },
  { type: "function", name: "weights", stateMutability: "view", inputs: [{ name: "p", type: "address" }], outputs: [{ type: "uint256" }] },
  { type: "function", name: "totalWeight", stateMutability: "view", inputs: [], outputs: [{ type: "uint256" }] },
];

const POOL_ABI = [
  { type: "function", name: "token0", stateMutability: "view", inputs: [], outputs: [{ type: "address" }] },
  { type: "function", name: "token1", stateMutability: "view", inputs: [], outputs: [{ type: "address" }] },
  { type: "function", name: "stable", stateMutability: "view", inputs: [], outputs: [{ type: "bool" }] },
];

let out = `/**
 * GENERATED by contracts/scripts/export-abi.mjs -- do not edit by hand.
 * Run \`node scripts/export-abi.mjs\` from the contracts/ directory after changing
 * a contract interface.
 */

`;

for (const [name, rel] of Object.entries(WANTED)) {
  const path = join(ROOT, "artifacts", rel);
  if (!existsSync(path)) {
    console.error(`missing artifact: ${rel} -- run \`npx hardhat compile\` first`);
    process.exit(1);
  }
  const { abi } = JSON.parse(readFileSync(path, "utf8"));
  // Keep only what a UI can call; drops constructors and bytecode noise.
  const slim = abi.filter((f) => f.type === "function" || f.type === "event" || f.type === "error");
  out += `export const ${name} = ${JSON.stringify(slim, null, 2)} as const;\n\n`;
}

out += `export const erc20Abi = ${JSON.stringify(ERC20_ABI, null, 2)} as const;\n\n`;
out += `export const voterAbi = ${JSON.stringify(VOTER_ABI, null, 2)} as const;\n\n`;
out += `export const poolAbi = ${JSON.stringify(POOL_ABI, null, 2)} as const;\n`;

const dest = join(ROOT, "..", "web", "lib", "abi.ts");
writeFileSync(dest, out);
console.log(`wrote ${dest}`);
